def update(interface):
    """Refresh copy without changing task order, defaults or pipeline overrides."""
    for task in interface['task']:
        if task['entry'] in TASK_DESCRIPTIONS:
            task['description'] = TASK_DESCRIPTIONS[task['entry']]
    for name, option in interface['option'].items():
        if name in OPTION_DESCRIPTIONS:
            option['description'] = OPTION_DESCRIPTIONS[name]
        for field in option.get('inputs', []):
            key = (name, field['name'])
            if key in INPUT_DESCRIPTIONS:
                field['description'] = INPUT_DESCRIPTIONS[key]
    return interface


